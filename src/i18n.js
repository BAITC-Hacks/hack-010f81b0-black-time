export function detectLocale(text, previous = 'kk') {
  if (/[әғқңөұүһі]|керек|одан|себет|жеткізу/iu.test(text)) return 'kk';
  if (/найди|найти|ищу|нуж[еннао]*|добав|корзин|характеристик|описани|наличи|доставк|оплат|минимал|подтверждаю|^да(?:$|\s|,)|^нет$/iu.test(text)) return 'ru';
  return previous;
}
