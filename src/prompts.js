// Optional provider-independent prompt builder. No LLM client, credentials or network.
export function buildMessages(context, locale = 'kk') {
  if (!['kk', 'ru'].includes(locale)) throw new TypeError('Invalid locale');
  return [{ role: 'system', content: `${SYSTEM_PROMPT}\nЖауап тілі: ${locale === 'ru' ? 'орысша (ru)' : 'қазақша (kk)'}.` },
    { role: 'user', content: `TRUSTED_CONTEXT (JSON деректері):\n${JSON.stringify(context)}` }];
}
